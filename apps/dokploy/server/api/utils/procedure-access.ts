import { db } from "@dokploy/server/db";
import { backups, schedules } from "@dokploy/server/db/schema";
import type { SuperSessionAccessKind } from "@dokploy/server/services/super-password";
import { eq } from "drizzle-orm";

type ProcedureAccessCtx = {
	user: { id: string; email?: string | null };
};

type ConditionalAccess = {
	dangerousWhen: (
		input: unknown,
		ctx: ProcedureAccessCtx,
	) => boolean | Promise<boolean>;
};

/**
 * Super password classification of every tRPC procedure in the app router.
 *
 * - "read": allowed for browser sessions and API keys.
 * - "write": allowed for browser sessions; API keys of a user with a super
 *   password need an open super session.
 * - "dangerous": a user with a super password needs a browser session and an
 *   open super session; API keys can never call it.
 *
 * Users without a super password keep today's behaviour. The router test in
 * __test__/security/super-session-procedure-access.test.ts fails when a
 * procedure is missing here, so procedures added by upstream merges must be
 * classified before they ship. Some procedures also check the super session
 * themselves for part of their input (Traefik TLS files, panel system
 * containers and volumes).
 */
export type ProcedureAccess = SuperSessionAccessKind | ConditionalAccess;

const asRecord = (input: unknown) =>
	input && typeof input === "object" ? (input as Record<string, unknown>) : {};

const changesLoginCredentials = (input: unknown, ctx: ProcedureAccessCtx) => {
	const { email, password, currentPassword } = asRecord(input);
	if (password || currentPassword) {
		return true;
	}
	return (
		typeof email === "string" &&
		email.trim().toLowerCase() !== (ctx.user.email ?? "").trim().toLowerCase()
	);
};

const isHostScheduleInput = (input: unknown) =>
	asRecord(input).scheduleType === "dokploy-server";

const isStoredHostSchedule = async (input: unknown) => {
	const { scheduleId } = asRecord(input);
	if (typeof scheduleId !== "string") {
		return false;
	}
	const schedule = await db.query.schedules.findFirst({
		where: eq(schedules.scheduleId, scheduleId),
		columns: { scheduleType: true },
	});
	return schedule?.scheduleType === "dokploy-server";
};

// A web server backup is a dump of the panel database, which stores every
// secret in clear.
const isWebServerBackupInput = (input: unknown) =>
	asRecord(input).databaseType === "web-server";

const isWebServerBackupUpdate = async (input: unknown) => {
	if (isWebServerBackupInput(input)) {
		return true;
	}
	const { backupId } = asRecord(input);
	if (typeof backupId !== "string") {
		return false;
	}
	const backup = await db.query.backups.findFirst({
		where: eq(backups.backupId, backupId),
		columns: { databaseType: true },
	});
	return backup?.databaseType === "web-server";
};

