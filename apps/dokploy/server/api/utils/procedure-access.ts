export const resolveProcedureAccess = async ({
	path,
	type,
	getRawInput,
	ctx,
}: {
	path: string;
	type: "query" | "mutation" | "subscription";
	getRawInput: () => Promise<unknown>;
	ctx: ProcedureAccessCtx;
}): Promise<SuperSessionAccessKind> => {
	const access = PROCEDURE_ACCESS[path];
	const byType: SuperSessionAccessKind = type === "query" ? "read" : "write";

	// A mutation or subscription is never weaker than a write, whatever the
	// table says, and unknown procedures fall back to their type.
	if (access === undefined || access === "read") {
		return byType;
	}
	if (typeof access === "string") {
		return access;
	}
	return (await access.dangerousWhen(await getRawInput(), ctx))
		? "dangerous"
		: byType;
};
